# Todas conta tem uma ordem de precedência, que é a seguinte: primeiro vem os parênteses(), depois a exponenciação**, depois a multiplicação *, divisão /, divisão inteira // e por último a adição + e subtração -. exemplo de como podemos utilizar a ordem de precedência para fazer uma operação matemática corretamente:

r2 = 5 + 3 * 2  
print(r2)  

r3 = 3*5+2**4
print(r3)