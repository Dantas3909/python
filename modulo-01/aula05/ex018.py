import math
angulo = float(input("Digite o valor do ângulo em graus: "))
print(f"O seno de {angulo} graus é {math.sin(math.radians(angulo)):.2f}")
print(f"O cosseno de {angulo} graus é {math.cos(math.radians(angulo)):.2f}")
print(f"A tangente de {angulo} graus é {math.tan(math.radians(angulo)):.2f}")
